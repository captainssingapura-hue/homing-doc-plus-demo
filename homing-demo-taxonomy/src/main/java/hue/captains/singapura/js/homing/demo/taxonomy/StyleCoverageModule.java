package hue.captains.singapura.js.homing.demo.taxonomy;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.demo.components.DemoComponentsCrate;
import hue.captains.singapura.js.homing.ui.look.LookModule;
import hue.captains.singapura.js.homing.ui.styles.Base;
import hue.captains.singapura.js.homing.ui.styles.HouseStyles;
import hue.captains.singapura.js.homing.ui.taxonomy.HouseTaxonomy;

import java.util.List;

/**
 * {@code STYLE_COVERAGE}: what each house style and palette says of each of the house's
 * components ({@link StyleCoverage}), derived from the answers once - the styles and palettes are
 * the house's constants - and written when served.
 */
public record StyleCoverageModule() implements EsModule<StyleCoverageModule>, SelfContent {

    public static final StyleCoverageModule INSTANCE = new StyleCoverageModule();

    public record STYLE_COVERAGE() implements Exportable._Constant<StyleCoverageModule> {}

    /** The matrix over the house: Base, the seven styles, the palettes; what wears the new sheet read from the crates the house's demos serve. */
    static final StyleCoverage HOUSE = StyleCoverage.of(HouseTaxonomy.INSTANCE.read(), Base.INSTANCE, HouseStyles.STYLES, HouseStyles.PALETTES,
            List.of(DemoComponentsCrate.INSTANCE), LookModule.INSTANCE);

    @Override public ImportsFor<StyleCoverageModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<StyleCoverageModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new STYLE_COVERAGE())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by StyleCoverageModule from the house's styles and palettes - do not hand-edit.",
                       "// A cell: [own looks, looks a base answers above the root, own treatments, treatments a base answers].",
                       "const STYLE_COVERAGE = Object.freeze(" + HOUSE.json() + ");");
    }
}
