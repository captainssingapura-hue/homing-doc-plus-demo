package hue.captains.singapura.js.homing.demo.components;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;
import java.util.stream.Collectors;

/**
 * The house's demos, as a page looks them up: {@code HOUSE_DEMOS[leaf]} is where the widget that
 * shows a leaf live is - {@code { module, export }}, the module's address and the class it exports,
 * by the leaf's token; {@code HOUSE_AROUND} the leaves the page around the demos shows, and where;
 * {@code HOUSE_PENDING} the realized leaves whose demos are still to come, and {@code
 * HOUSE_UNREALIZED} those nothing realizes yet. Generated from {@link HouseDemos}, so no second list
 * can drift from it.
 *
 * <p>It imports no demo: a page loads a demo's module when the leaf is first shown, so opening the
 * page loads none of them, and showing one leaf loads only its demo. The addresses are the
 * modules' own, as every import has them, so a demo loaded late shares every module the page has
 * already - the parties, the steward, the house's look.</p>
 */
public record HouseDemosModule() implements EsModule<HouseDemosModule>, SelfContent {

    public static final HouseDemosModule INSTANCE = new HouseDemosModule();

    public record HOUSE_DEMOS() implements Exportable._Constant<HouseDemosModule> {}

    public record HOUSE_AROUND() implements Exportable._Constant<HouseDemosModule> {}

    public record HOUSE_PENDING() implements Exportable._Constant<HouseDemosModule> {}

    public record HOUSE_UNREALIZED() implements Exportable._Constant<HouseDemosModule> {}

    @Override public ImportsFor<HouseDemosModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<HouseDemosModule> exports() {
        return new ExportsOf<>(INSTANCE, List.of(new HOUSE_DEMOS(), new HOUSE_AROUND(), new HOUSE_PENDING(), new HOUSE_UNREALIZED()));
    }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        var house = HouseDemos.INSTANCE;
        String demos = house.demos().stream()
                .map(d -> quoted(d.leaf().token()) + ": Object.freeze({ module: " + quoted(resolver.resolve(d.module()).basePath())
                        + ", export: " + quoted(d.className()) + " })")
                .collect(Collectors.joining(",\n    "));
        String around = house.aroundIt().stream()
                .map(a -> quoted(a.leaf().token()) + ": " + quoted(a.where()))
                .collect(Collectors.joining(", "));
        String pending = house.pending().stream().map(c -> quoted(c.token())).collect(Collectors.joining(", "));
        String unrealized = house.unrealized().stream().map(c -> quoted(c.token())).collect(Collectors.joining(", "));
        return List.of(
                "// Generated by HouseDemosModule from HouseDemos - do not hand-edit: where the widget that shows each leaf live is,",
                "// loaded when the leaf is first shown.",
                "const HOUSE_DEMOS = Object.freeze({\n    " + demos + "\n});",
                "// Shown by the page around the demos, and where.",
                "const HOUSE_AROUND = Object.freeze({ " + around + " });",
                "// Realized, their demos still to come.",
                "const HOUSE_PENDING = Object.freeze([" + pending + "]);",
                "// Realized by nothing yet.",
                "const HOUSE_UNREALIZED = Object.freeze([" + unrealized + "]);");
    }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
