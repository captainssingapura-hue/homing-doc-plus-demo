package hue.captains.singapura.js.homing.demo.workspacewidgets.platformer;

import hue.captains.singapura.js.homing.conformance.rules.ConformanceDebt;
import hue.captains.singapura.js.homing.conformance.rules.NoRawCssRule;
import hue.captains.singapura.js.homing.core.DomModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleImports;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.ui.look.HouseDesigns;

import java.util.List;

/**
 * The house's platformer scene as a page has it: one stateless object, {@code HousePlatformerScene}, generated from
 * the design. It wears and sheds a leaf of the scene on an element, asked by the leaf's constant, and refuses a leaf
 * of another branch; it imports the design's sheet, so the sheet loads wherever the design is used. A DOM module,
 * honestly: what it does is put its classes on an element, as the grid's design does its own.
 */
@ConformanceDebt(rule = NoRawCssRule.class, findings = 5,
        reason = "The design's object, generated by core's DesignObject, is its classes' manager - it puts them on and takes them off itself, as the look does its own - and the rule has no allowance for a generated design object yet: an allowance in the rule for one pays it.")
public record HousePlatformerSceneModule() implements DomModule<HousePlatformerSceneModule>, SelfContent {

    public static final HousePlatformerSceneModule INSTANCE = new HousePlatformerSceneModule();

    /** The design's object: {@code HousePlatformerScene.wear(PLATFORMER_SCENE.PLATFORM, el)}. */
    public record HousePlatformerScene() implements Exportable._Constant<HousePlatformerSceneModule> {}

    @Override
    public ImportsFor<HousePlatformerSceneModule> imports() {
        return ImportsFor.<HousePlatformerSceneModule>builder()
                .add(new ModuleImports<>(List.of(new HousePlatformerSceneSheet.house_platformer_scene_sheet()), HousePlatformerSceneSheet.INSTANCE))
                .build();
    }

    @Override public ExportsOf<HousePlatformerSceneModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new HousePlatformerScene())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return HouseDesigns.INSTANCE.object(hue.captains.singapura.js.homing.demo.workspacewidgets.platformer.HousePlatformerScene.INSTANCE, "house_platformer_scene_sheet");
    }
}
